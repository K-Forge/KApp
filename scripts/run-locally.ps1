switch ($Command) {
    'up' {
        New-Secrets
        Write-Host 'Building and starting the stack. The first time takes a while: Maven builds six services.'
        Invoke-Compose up -d --build
        $gateway = Get-EnvValue 'KAPP_GATEWAY_PORT' '8080'
        $portal = Get-EnvValue 'KAPP_PORTAL_PORT' '4300'
        $oidc = Get-EnvValue 'KAPP_FAKE_OIDC_PORT' '8090'
        Wait-For "http://localhost:$gateway/auth/health" 'the backend' 15
        Wait-For "http://localhost:$portal/health" 'the admin portal' 5
        Write-Host @"

KApp is running on this computer.

  API (gateway)     http://localhost:$gateway        the Android emulator reaches it at http://10.0.2.2:$gateway
  Admin portal      http://localhost:$portal
  Sign-in (fake)    http://localhost:$oidc/kapp      stands in for Microsoft

Sign in with Microsoft and type one of these as the user name; there is no password:

  estudiante        a student, with the test SINU's record, timetable and semaforo
  profesor          a professor
  administrativo    staff, and the portal's administrator

The app: docs/RUN-LOCALLY.md, "The Android app". Stop with: .\scripts\run-locally.ps1 down
"@
    }
    'status' { Invoke-Compose ps }
    'logs' { Invoke-Compose logs -f --tail=60 }
    'down' { Invoke-Compose down }
    'reset' {
        Invoke-Compose down -v
        # Only a local .env: the team's points at Atlas and is never this script's to delete.
        if (Test-LocalEnv) { Remove-Item $EnvFile }
        Write-Host "Stopped, and the local data and secrets deleted. The next 'up' starts over."
    }
}
