# Runs the whole KApp backend and the admin portal on this computer, from PowerShell: the same as
# scripts/run-locally.sh, for Windows without Git Bash. docs/RUN-LOCALLY.md is the walkthrough.
#
#   .\scripts\run-locally.ps1            # up: secrets on first run, then build and start everything
#   .\scripts\run-locally.ps1 status     # what is running
#   .\scripts\run-locally.ps1 logs       # follow the logs
#   .\scripts\run-locally.ps1 down       # stop, keeping the data
#   .\scripts\run-locally.ps1 reset      # stop and delete the data and the secrets
#
# Only Docker Desktop is needed. The secrets are generated by scripts/run-locally.sh itself, run
# once inside a small Linux container, so they come out exactly as on macOS or Linux and nothing
# else has to be installed. If PowerShell refuses to run the script, allow it for this window:
#
#   Set-ExecutionPolicy -Scope Process -ExecutionPolicy Bypass

param([ValidateSet('up', 'status', 'logs', 'down', 'reset')] [string] $Command = 'up')

$ErrorActionPreference = 'Stop'
$Repo = Split-Path -Parent $PSScriptRoot
$Dir = Join-Path $Repo 'app/backend/microservices'
$EnvFile = Join-Path $Dir '.env'
$Profiles = @('--profile', 'local-db', '--profile', 'academic', '--profile', 'map', '--profile', 'dev')

function Invoke-Compose {
    # Always the `kapp-local` project, whatever .env says (see run-locally.sh).
    $env:KAPP_STACK = 'local'
    $env:KAPP_PROJECT = 'kapp-local'
    Push-Location $Dir
    try { docker compose @Profiles @args; if ($LASTEXITCODE -ne 0) { throw "docker compose $args failed" } }
    finally { Pop-Location }
}

function Test-Docker {
    docker info *> $null
    if ($LASTEXITCODE -ne 0) { throw 'Docker is not running. Start Docker Desktop and try again.' }
}

function Test-LocalEnv {
    (Test-Path $EnvFile) -and (Select-String -Path $EnvFile -Pattern '^MONGO_ROOT_PASSWORD=.' -Quiet)
}

function New-Secrets {
    if (Test-Path $EnvFile) {
        if (-not (Test-LocalEnv)) {
            throw 'app/backend/microservices/.env exists and points at another database. Move it aside to run locally.'
        }
        return
    }
    Write-Host 'Writing app/backend/microservices/.env: secrets generated on this computer, for it alone.'
    docker run --rm -v "${Repo}:/repo" -w /repo alpine:3.20 sh -c 'apk add --no-cache bash openssl > /dev/null && bash scripts/run-locally.sh secrets'
    if ($LASTEXITCODE -ne 0) { throw 'Could not generate the secrets.' }
}

function Get-EnvValue([string] $Name, [string] $Default) {
    $line = Select-String -Path $EnvFile -Pattern "^$Name=(.*)$" | Select-Object -Last 1
    if ($line) { $v = $line.Matches[0].Groups[1].Value.Trim("'", '"'); if ($v) { return $v } }
    return $Default
}

function Wait-For([string] $Url, [string] $What, [int] $Minutes) {
    Write-Host -NoNewline "Waiting for $What "
    for ($i = 0; $i -lt $Minutes * 12; $i++) {
        try {
            Invoke-WebRequest -Uri $Url -UseBasicParsing -TimeoutSec 5 | Out-Null
            Write-Host '- up.'
            return
        } catch { Write-Host -NoNewline '.'; Start-Sleep -Seconds 5 }
    }
    throw "$What did not answer at $Url. See: .\scripts\run-locally.ps1 logs"
}

